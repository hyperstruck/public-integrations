"""Where in a repository a coding-session step happened, as one bounded string.

Independent of Core: this client cannot import ``hyperstruck_core`` (see
``no_engine_import_test.py``), so the format is reimplemented here rather than shared.
``locator_test.py`` pins this against golden cases generated from Core's own builder at
the pinned version (``locator_golden_cases.json``, regenerated by
``scripts/generate_locator_golden_cases.py`` in core-platform), so the two cannot drift
apart without a red test naming which case moved.
"""

from __future__ import annotations

import re
from urllib.parse import urlsplit

LOCATOR_SCHEME = "git:"
LOCATOR_MAX_CHARS = 200

_SHA = re.compile(r"^(?:[0-9a-f]{40}|[0-9a-f]{64})$")
_SCP_REMOTE = re.compile(r"^(?:[^@/:]+@)?(?P<host>[^/:]+):(?P<path>[^/].*)$")
_FILESYSTEM_PREFIXES = ("/", "./", "../", "~", "file:")


def repository_from_remote(remote: str | None) -> str | None:
    """``host/owner/repo`` for a remote, or None when it names no hosted repository."""
    text = (remote or "").strip()
    if not text or text.startswith(_FILESYSTEM_PREFIXES):
        return None
    if "://" in text:
        parts = urlsplit(text)
        host, path = parts.hostname, parts.path
    elif match := _SCP_REMOTE.match(text):
        host, path = match["host"], match["path"]
    else:
        return None
    segments = [
        segment
        for segment in (path or "").removesuffix("/").removesuffix(".git").split("/")
        if segment
    ]
    if not host or len(segments) < 2:
        return None
    return "/".join((host.lower(), *segments))


def safe_repository_path(path: str | None) -> str | None:
    """A repository-relative path, or None when it could name something outside it."""
    text = (path or "").strip()
    if not text or text.startswith("/") or "\\" in text or any(ord(char) < 32 for char in text):
        return None
    segments = text.split("/")
    if any(segment in ("", ".", "..") for segment in segments):
        return None
    return text


def locator_from_parts(
    remote: str | None,
    commit: str | None = None,
    tree: str | None = None,
    path: str | None = None,
    *,
    max_chars: int = LOCATOR_MAX_CHARS,
) -> str | None:
    """The locator for these parts, dropping what is malformed and, over the bound, the

    path then the tree. A tree is only meaningful beside the commit it belongs to.
    """
    repository = repository_from_remote(remote)
    if repository is None:
        return None
    full_commit = (
        (commit or "").strip().lower() if _SHA.match((commit or "").strip().lower()) else ""
    )
    full_tree = (
        (tree or "").strip().lower()
        if full_commit and _SHA.match((tree or "").strip().lower())
        else ""
    )
    safe_path = safe_repository_path(path) or ""
    base = f"{LOCATOR_SCHEME}{repository}" + (f"@{full_commit}" if full_commit else "")
    tree_part = f"^{{tree:{full_tree}}}" if full_tree else ""
    path_part = f":{safe_path}" if safe_path else ""
    for candidate in (base + tree_part + path_part, base + tree_part, base):
        if len(candidate) <= max_chars:
            return candidate
    return None
